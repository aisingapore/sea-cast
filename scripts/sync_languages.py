#!/usr/bin/env python3
# /// script
# requires-python = ">=3.13"
# dependencies = ["pyyaml"]
# ///
"""Generate typed language constants for backend + frontend from languages.yaml.

`languages.yaml` is the single source of truth for language support in the app.
This script generates the necessary frontend/backend files from the YAML:

  - backend/app/languages.py    (Literals + preset dicts, mypy-checked)
  - frontend/src/lib/languages.ts (const arrays + derived types, tsc-checked)

The frontend only gets the app language lists and display overrides. Each profile's
resolved languages are read from the server (GET /stt-profiles, GET /translators).

Both generated files are committed and must stay in sync with the YAML. CI runs
this script with --check and fails if they drift.

Run:
    uv run scripts/sync_languages.py          # write
    uv run scripts/sync_languages.py --check  # verify

uv reads the dependencies from the inline metadata block at the top (PEP 723) and
runs the script in its own cached environment.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
YAML_PATH = ROOT / "languages.yaml"
PY_OUT = ROOT / "backend" / "app" / "languages.py"
TS_OUT = ROOT / "frontend" / "src" / "lib" / "languages.ts"

AUTO = "auto"
REGENERATE_COMMAND = "uv run scripts/sync_languages.py"
BANNER_LINES = (
    "Generated by scripts/sync_languages.py from languages.yaml",
    f"DO NOT EDIT BY HAND — regenerate with: {REGENERATE_COMMAND}",
)


def _resolve_capability_list(
    capability: list[str], excludes: list[str], app_langs: list[str]
) -> list[str]:
    """Return app languages a model supports.

    ["*"] means every app language minus any excluded language.

    Args:
        capability: The list of languages supported by a model.
        excludes: The list of languages supported by the app but
            not the model.
        app_langs: The list of languages supported by the app.

    Returns:
        The app languages the model supports, in app order (to
        ensure the generated files are the same on every run).
    """
    if capability == ["*"]:
        return [lang for lang in app_langs if lang not in set(excludes)]
    return [lang for lang in app_langs if lang in set(capability)]


@dataclass
class STTSettings:
    """An STT model family's language support, parsed from languages.yaml.

    Attributes:
        recognizes: List of languages the model can process, or ["*"] which
            means all app-supported languages can be processed.
        supports_auto: Whether the model can automatically detect the language.
        auto_only: Whether the model ONLY supports automatic detection.
            (``supports_auto`` must be True)
        code_overrides: Mapping for language codes if the model uses a
            different set of codes from the app's. (e.g. {"fil": "tl"})
        excludes: List of languages supported by the app but not the model
            (only applies when ``recognizes`` is ["*"]).
    """

    recognizes: list[str] = field(default_factory=list)
    supports_auto: bool = False
    auto_only: bool = False
    code_overrides: dict[str, str] = field(default_factory=dict)
    excludes: list[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        """Coerce fields to their types and validate the auto-detect settings."""
        self.recognizes = list(self.recognizes)
        self.supports_auto = bool(self.supports_auto)
        self.auto_only = bool(self.auto_only)
        self.code_overrides = dict(self.code_overrides)
        self.excludes = list(self.excludes)
        # Auto-only without auto-detect would leave no selectable language.
        if self.auto_only and not self.supports_auto:
            raise ValueError("auto_only: true needs supports_auto: true")

    def resolve_capabilities(self, source_languages: list[str]) -> dict[str, Any]:
        """Resolve the model's languages against the app's and return its capabilities.

        Args:
            source_languages: The app's source (spoken) languages.

        Returns:
            A dictionary containing the model's recognized languages (resolved
            against the app's languages), whether it supports auto-detection
            (exclusively or not) and any language code mappings that the
            model requires.
        """
        return {
            "recognizes": _resolve_capability_list(
                self.recognizes, self.excludes, source_languages
            ),
            "supports_auto": self.supports_auto,
            "auto_only": self.auto_only,
            "code_overrides": self.code_overrides,
        }


@dataclass
class TranslatorSettings:
    """A translator model family's language support, parsed from languages.yaml.

    Attributes:
        translates_to: List of languages that the translation model supports, or
            ["*"] which means all app-supported languages can be processed.
        excludes: List of languages supported by the app but not the model
            (only applies when ``translates_to`` is ["*"]).
    """

    translates_to: list[str] = field(default_factory=list)
    excludes: list[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        """Coerce fields to their types."""
        self.translates_to = list(self.translates_to)
        self.excludes = list(self.excludes)

    def resolve_capabilities(self, target_languages: list[str]) -> dict[str, Any]:
        """Resolve the model's languages against the app's and return its capabilities.

        Args:
            target_languages: The app's target languages.

        Returns:
            A dictionary containing the model's target languages, resolved against
            the app's languages.
        """
        return {
            "translates_to": _resolve_capability_list(
                self.translates_to, self.excludes, target_languages
            ),
        }


class LanguageSettings:
    """The app's languages and each preset's capabilities resolved against them.

    Attributes:
        source_languages: The app's source (spoken) languages.
        target_languages: The app's target (translation) languages.
        display_overrides: {language code: display name}, where CLDR's isn't ideal.
        stt_models: {preset name: resolved STT capabilities}.
        translator_models: {preset name: resolved translator capabilities}.
    """

    def __init__(self, data: dict[str, Any]) -> None:
        """Parse languages.yaml's data and resolve every preset against the app.

        Args:
            data: languages.yaml, as loaded by yaml.safe_load.

        Raises:
            ValueError: An STT preset sets auto_only without supports_auto.
        """
        self.source_languages: list[str] = list(data["app"]["source"])
        self.target_languages: list[str] = list(data["app"]["target"])
        self.display_overrides: dict[str, str] = dict(data.get("display_overrides", {}))
        self.stt_models: dict[str, dict[str, Any]] = {
            name: STTSettings(**config).resolve_capabilities(self.source_languages)
            for name, config in data["stt_models"].items()
        }
        self.translator_models: dict[str, dict[str, Any]] = {
            name: TranslatorSettings(**config).resolve_capabilities(
                self.target_languages
            )
            for name, config in (data["translator_models"] or {}).items()
        }


# ── Python renderer ──────────────────────────────────────────────────────────


def _py_tuple(codes: list[str]) -> str:
    items = ", ".join(f'"{c}"' for c in codes)
    if len(codes) == 1:
        items += ","
    return f"({items})"


def _py_frozenset(codes: list[str]) -> str:
    if not codes:
        return "frozenset()"
    return "frozenset({" + ", ".join(f'"{c}"' for c in codes) + "})"


def _py_literal(codes: list[str]) -> str:
    return "Literal[" + ", ".join(f'"{c}"' for c in codes) + "]"


def _py_dict(mapping: dict[str, str]) -> str:
    return "{" + ", ".join(f'"{k}": "{v}"' for k, v in mapping.items()) + "}"


def render_python(settings: LanguageSettings) -> str:
    """Render the source of backend/app/languages.py.

    Args:
        settings: Language settings as parsed from languages.yaml.

    Returns:
        The .py file in string form.
    """
    banner = "\n".join(f"# {line}" for line in BANNER_LINES)
    stt_rows = "\n".join(
        f'    "{name}": {{"recognizes": {_py_frozenset(cfg["recognizes"])}, '
        f'"supports_auto": {cfg["supports_auto"]}, "auto_only": {cfg["auto_only"]}, '
        f'"code_overrides": {_py_dict(cfg["code_overrides"])}}},'
        for name, cfg in settings.stt_models.items()
    )
    translator_rows = "\n".join(
        f'    "{name}": {{"translates_to": {_py_frozenset(cfg["translates_to"])}}},'
        for name, cfg in settings.translator_models.items()
    )
    override_rows = "\n".join(
        f'    "{code}": "{name}",' for code, name in settings.display_overrides.items()
    )
    return f'''\
{banner}
from typing import Literal, TypedDict

AUTO = "{AUTO}"

APP_SOURCE: tuple[str, ...] = {_py_tuple(settings.source_languages)}
APP_TARGET: tuple[str, ...] = {_py_tuple(settings.target_languages)}

InputLanguage = {_py_literal([AUTO, *settings.source_languages])}
TargetLanguage = {_py_literal(settings.target_languages)}


class STTSettings(TypedDict):
    recognizes: frozenset[str]
    supports_auto: bool
    auto_only: bool
    code_overrides: dict[str, str]


# Language presets by model family as defined in languages.yaml.
STT_MODELS: dict[str, STTSettings] = {{
{stt_rows}
}}


class TranslatorSettings(TypedDict):
    translates_to: frozenset[str]


TRANSLATOR_MODELS: dict[str, TranslatorSettings] = {{
{translator_rows}
}}

DISPLAY_OVERRIDES: dict[str, str] = {{
{override_rows}
}}
'''


# ── TypeScript renderer ────────────────────────────────────────────────────────


def _ts_array(codes: list[str]) -> str:
    return "[" + ", ".join(f'"{c}"' for c in codes) + "]"


def render_typescript(settings: LanguageSettings) -> str:
    """Render the source of frontend/src/lib/languages.ts.

    Args:
        settings: Language settings as parsed from languages.yaml.

    Returns:
        The .ts file in string form.
    """
    banner = "\n".join(f"// {line}" for line in BANNER_LINES)
    override_rows = "\n".join(
        f'  "{code}": "{name}",' for code, name in settings.display_overrides.items()
    )
    return f'''\
{banner}

export const AUTO = "{AUTO}" as const;

export const APP_SOURCE = {_ts_array(settings.source_languages)} as const;
export const APP_TARGET = {_ts_array(settings.target_languages)} as const;

export type InputLanguage = (typeof APP_SOURCE)[number] | typeof AUTO;
export type TargetLanguage = (typeof APP_TARGET)[number];

export const DISPLAY_OVERRIDES: Record<string, string> = {{
{override_rows}
}};
'''


# ── Entry point ────────────────────────────────────────────────────────────────


def main() -> int:
    """Write the generated language files, or with --check, verify they're current.

    --check writes nothing; it compares each file with what would be generated
    and lists any that differ (CI runs it to catch a stale or hand-edited file).

    Returns:
        The exit code: 1 if --check found a stale file, else 0.
    """
    data = yaml.safe_load(YAML_PATH.read_text())
    settings = LanguageSettings(data)
    outputs = {PY_OUT: render_python(settings), TS_OUT: render_typescript(settings)}

    check = "--check" in sys.argv[1:]
    stale: list[str] = []
    for path, content in outputs.items():
        rel = path.relative_to(ROOT)
        if check:
            current = path.read_text() if path.exists() else None
            if current != content:
                stale.append(str(rel))
        else:
            path.write_text(content)
            print(f"wrote {rel}")

    if check and stale:
        print(
            "ERROR: generated language files are out of date:\n  "
            + "\n  ".join(stale)
            + f"\nRun: {REGENERATE_COMMAND}",
            file=sys.stderr,
        )
        return 1
    if check:
        print("Language files are up to date ✓")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
